function makeTelemetry(durationSec: number, batteryUsed: number, coverage: number, distanceKm: number) {
  const steps = 24;
  return Array.from({ length: steps + 1 }, (_, i) => {
    const f = i / steps;
    return {
      t: Math.round(durationSec * f),
      battery: Math.round((100 - batteryUsed * f) * 10) / 10,
      altitude: i === 0 ? 0 : 78 + Math.sin(f * 9) * 5,
      speed: i === 0 ? 0 : 7.4 + Math.cos(f * 7) * 1.1,
      coverage: Math.round(coverage * f * 1000) / 10,
      distance: Math.round(distanceKm * f * 100) / 100,
    };
  });
}

function polyAround(center: LatLng, r: number): LatLng[] {
  return circlePolygon(center, r, 6);
}

